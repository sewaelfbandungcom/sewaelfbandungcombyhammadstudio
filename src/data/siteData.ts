export function getWhatsAppBookingUrl(options?: {
  unitName?: string;
  category?: string;
  destination?: string;
  date?: string;
  passengerCount?: number | string;
  phone?: string;
}) {
  const targetPhone = options?.phone || primaryWhatsApp;
  let text = "Halo admin sewaelfbandung.com,\n\nSaya ingin sewa / reservasi kendaraan:";
  
  if (options?.unitName) {
    text += `\n• Unit Armada: ${options.unitName}`;
  }
  if (options?.destination) {
    text += `\n• Tujuan: ${options.destination}`;
  }
  if (options?.passengerCount) {
    text += `\n• Estimasi Rombongan: ${options.passengerCount} Orang`;
  }
  if (options?.date) {
    text += `\n• Tanggal Keberangkatan: ${options.date}`;
  }
  
  text += "\n\nMohon info ketersediaan unit dan penawaran harga terbaiknya. Terima kasih!";
  return `https://wa.me/${targetPhone}?text=${encodeURIComponent(text)}`;
}

